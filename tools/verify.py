"""Static verification: XML well-formedness, paren balance, allowed functions, field refs, coverage. Run from repo root."""
import os, re, sys, glob
import xml.etree.ElementTree as ET
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))
ALLOWED = "ABS ACOS ADDMONTHS AND ASCII ASIN ATAN ATAN2 BEGINS BLANKVALUE BR CASE CASESAFEID CEILING CHR CONTAINS COS CURRENCYRATE DATE DATETIMEVALUE DATEVALUE DAY DAYOFYEAR DISTANCE EXP FIND FLOOR FORMATDURATION FROMUNIXTIME GEOLOCATION GETSESSIONID HOUR IF INCLUDES INITCAP ISBLANK ISCHANGED ISCLONE ISNEW ISNULL ISNUMBER ISOWEEK ISOYEAR ISPICKVAL LEFT LEN LN LOG LOWER LPAD MAX MCEILING MFLOOR MID MILLISECOND MIN MINUTE MOD MONTH NOT NOW NULLVALUE OR PI PICKLISTCOUNT PRIORVALUE REGEX REVERSE RIGHT ROUND RPAD SECOND SIN SQRT SUBSTITUTE TAN TEXT TIMENOW TIMEVALUE TODAY TRIM TRUNC UNIXTIMESTAMP UPPER VALUE VLOOKUP WEEKDAY YEAR".split()
ALLOWED_SET = set(ALLOWED)
NS = {"m": "http://soap.sforce.com/2006/04/metadata"}
errs = []; cov = {f: [] for f in ALLOWED}
xmlfiles = glob.glob("force-app/**/*.xml", recursive=True)
for p in xmlfiles:
    try: ET.parse(p)
    except Exception as e: errs.append(f"XML {p}: {e}")
fields = {}
for p in glob.glob("force-app/main/default/objects/*/fields/*.field-meta.xml"):
    o = p.split("/objects/")[1].split("/")[0]; n = os.path.basename(p).split(".")[0]
    fields.setdefault(o, {"Name", "Id", "CreatedDate", "OwnerId", "Description", "StageName", "CloseDate"})
    fields[o].add(n)
    if n.endswith("__c"):
        import xml.etree.ElementTree as _E
        if _E.parse(p).getroot().find("m:type", NS).text == "Location":
            fields[o] |= {n.replace("__c", "__latitude__s"), n.replace("__c", "__longitude__s")}
for o in os.listdir("force-app/main/default/objects"): fields.setdefault(o, {"Name", "Id"})
nrules = 0; maxlen = 0; stats = []
for p in sorted(glob.glob("force-app/**/validationRules/*.xml", recursive=True)):
    nrules += 1
    obj = p.split("/objects/")[1].split("/")[0]; rname = os.path.basename(p).split(".")[0]
    t = ET.parse(p).getroot()
    fx = t.find("m:errorConditionFormula", NS).text
    for tag in ("active", "description", "errorMessage"):
        if t.find(f"m:{tag}", NS) is None: errs.append(f"{rname}: missing {tag}")
    if t.find("m:active", NS).text != "true": errs.append(f"{rname}: inactive")
    maxlen = max(maxlen, len(fx))
    if len(fx) >= 3900: errs.append(f"{rname}: too long {len(fx)}")
    # strip string literals
    bare = re.sub(r"'(?:[^'\\]|\\.)*'", "''", fx)
    depth = 0; mx = 0
    for ch in bare:
        if ch == "(": depth += 1; mx = max(mx, depth)
        elif ch == ")": depth -= 1
        if depth < 0: break
    if depth != 0: errs.append(f"{rname}: paren imbalance {depth}")
    if fx.count("'") % 2: errs.append(f"{rname}: odd quotes")
    used = set()
    for m in re.finditer(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", bare):
        fn = m.group(1).upper()
        if fn not in ALLOWED_SET: errs.append(f"{rname}: disallowed fn {m.group(1)}")
        else: used.add(fn); cov[fn].append(rname)
    # field refs: identifiers not followed by '(' and not keywords
    ids = set(re.findall(r"(?<![\w$.])([A-Za-z][A-Za-z0-9_]*(?:__[cs])?)\b(?!\s*\()", bare))
    skip = {"TRUE", "FALSE", "ObjectType"}
    for i in ids:
        if i.upper() in skip or i in ("Fields",): continue
        if i not in fields[obj]: errs.append(f"{rname}: unknown field/id {i} on {obj}")
    # $ObjectType refs
    for mo in re.finditer(r"\$ObjectType\.(\w+)\.Fields\.(\w+)", bare):
        o2, f2 = mo.groups()
        if f2 not in fields.get(o2, set()): errs.append(f"{rname}: bad $ObjectType ref {o2}.{f2}")
    stats.append((rname, len(used), mx))
missing = [f for f, v in cov.items() if not v]
print("xml files:", len(xmlfiles), "| rules:", nrules, "| max formula len:", maxlen)
print("min distinct fns/rule:", min(s[1] for s in stats), "| rules with <4 distinct fns:", [s[0] for s in stats if s[1] < 4])
print("max nesting >=3 rules:", sum(1 for s in stats if s[2] >= 3), "of", nrules)
print("uncovered functions:", missing or "none")
print("errors:", len(errs)); [print(" ", e) for e in errs]
if "--coverage" in sys.argv:
    with open("COVERAGE.md", "w") as f:
        f.write("# Function Coverage\n\nEvery allowed function mapped to the validation rules that use it. Generated by `tools/verify.py --coverage`.\n\n")
        f.write(f"Total rules: {nrules}. Uncovered functions: {', '.join(missing) or 'none'}.\n\n| Function | Rules (count) | Examples |\n|---|---|---|\n")
        for fn in ALLOWED:
            rs = sorted(set(cov[fn]))
            f.write(f"| `{fn}` | {len(rs)} | {', '.join(rs[:4])}{' ...' if len(rs) > 4 else ''} |\n")
sys.exit(1 if errs else 0)
